#[cfg(test)]
mod tests {
    use rand_core::{Rng, SeedableRng};

    use original_chacha::ChaCha8Rng as OracleRng;
    extern crate alloc;
    use alloc::alloc::{Layout, alloc, dealloc};

    use super::*;

    #[repr(C, packed(4))]
    struct LastRow {
        a: u32,
        b: u64,
        c: u32,
    }

    impl LastRow {
        #[inline(always)]
        pub fn new(a: u32, b: u64, c: u32) -> Self {
            Self {
                a: a.to_le(),
                b: b.to_le(),
                c: c.to_le(),
            }
        }

        #[inline(always)]
        pub fn as_u32_ptr(&self) -> *const u32 {
            let struct_pointer: *const Self = self;
            struct_pointer as *const u32
        }
    }

    #[test]
    fn set_last_row() {
        let mut rng_1 = ChaCha8Rng::from_seed([0u8; 32]);
        let mut rng_2 = ChaCha8Rng::from_seed([0u8; 32]);

        rng_1.set_stream(1);
        rng_1.set_block_pos(1);

        let last_row = LastRow::new(1, 1 << 32, 0);
        unsafe {
            rng_2.set_last_row(last_row.as_u32_ptr());
        }
        assert_eq!(rng_1.next_u32(), rng_2.next_u32());
    }

    #[test]
    fn rng_fill_bytes_tests() {
        let mut oracle = OracleRng::from_seed([0u8; 32]);
        let mut test_rng = ChaCha8Rng::from_seed([0u8; 32]);

        let mut arr = [0u8; 4096];
        let mut test = [0u8; 4096];

        for _ in 0..10 {
            for size in 1..4096 {
                let word_pos = oracle.get_word_pos();
                oracle.fill_bytes(&mut arr[0..size]);
                test_rng.fill_bytes(&mut test[0..size]);
                for byte in 0..size {
                    let word = word_pos + (byte as u128 / 4);
                    assert!(
                        arr[byte] == test[byte],
                        "Inequal byte at byte #{}, word #{}, state #{}, o = {} != {}, size = {}",
                        byte,
                        word,
                        word % 16,
                        arr[byte],
                        test[byte],
                        size
                    );
                }
            }
        }
    }

    #[test]
    fn aligned_fill_bytes() {
        let size = 4096;

        let layout = Layout::from_size_align(size, 16).unwrap();
        let ptr = unsafe { alloc(layout) };

        assert_eq!(ptr as usize & 0xF, 0);

        let test = unsafe { core::slice::from_raw_parts_mut(ptr, size) };

        let mut oracle = OracleRng::from_seed([0u8; 32]);
        let mut test_rng = ChaCha8Rng::from_seed([0u8; 32]);

        let mut arr = [0u8; 4096];

        for _ in 0..10 {
            for size in 1..4096 {
                let word_pos = oracle.get_word_pos();
                oracle.fill_bytes(&mut arr[0..size]);
                test_rng.fill_bytes(&mut test[0..size]);
                for byte in 0..size {
                    let word = word_pos + (byte as u128 / 4);
                    assert!(
                        arr[byte] == test[byte],
                        "Inequal byte at byte #{}, word #{}, state #{}, o = {} != {}, size = {}",
                        byte,
                        word,
                        word % 16,
                        arr[byte],
                        test[byte],
                        size
                    );
                }
            }
        }
        unsafe { dealloc(ptr, layout) };
    }

    #[test]
    fn next_u64_tests() {
        let mut rng = ChaCha8Rng::from_seed([0u8; 32]);
        for _ in 0..100 {
            assert_ne!(rng.next_u64(), 0);
        }
    }
}
